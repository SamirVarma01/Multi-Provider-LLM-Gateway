func renderFile(path string, w io.Writer) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var res Results
	if err := json.Unmarshal(b, &res); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if res.Audit == nil {
		return errors.New(path + ": no audit")
	}
	return renderMarkdown(&res, w)
}

type printer struct {
	w   io.Writer
	err error
}

func (p *printer) f(format string, args ...any) {
	if p.err == nil {
		_, p.err = fmt.Fprintf(p.w, format, args...)
	}
}

func renderMarkdown(res *Results, w io.Writer) error {
	p := &printer{w: w}
	m, s, a, ch := res.Meta, res.Meta.Settings, res.Audit, res.Checks
	h := res.Headline()
	p.f("# Ledger through crashes\n\n")
	p.f("Generated by `scripts/ledger_chaos` on %s", m.Date)
	if m.Commit != "" {
		p.f(" at commit `%s`", m.Commit)
	}
	p.f(". Host: %s.\n\n", orUnknown(m.Host))
	p.f("Load ran at %s req/s from %s keys for %.0fs, spread over three aliases: `bench` (OpenAI format), ", s["rate"], s["keys"], res.Load.DurationMs/1000)
	p.f("`failover` (OpenAI format, two targets, the first failing %s of attempts before any output) and `bench-claude` (Anthropic format). ", pct(s["primary_errors"]))
	p.f("Half the requests streamed, `max_tokens` ranged from 16 to 96, and half the streams asked for usage. ")
	p.f("Every mock response takes about a second (first token after %s, then %s tokens at %s tokens/s), so many requests are in flight at each kill.\n\n", s["mock_ttft"], s["mock_tokens"], s["mock_tps"])
	p.f("The gateway's container was killed %d times with SIG%s, after running %s each time, and started again after %s. ", len(res.Kills), s["signals"], s["up"], s["down"])
	p.f("Load continued through the restarts and for %s after the last one. ", s["tail"])
	p.f("The gateway ran with `REQUEST_TIMEOUT=%s` and `RECONCILE_GRACE=%s`, and its reconciler ran every 5s throughout. ", s["request_timeout"], s["reconcile_grace"])
	p.f("Once every reservation was older than the sum of the two, the test ran the reconciler until nothing was left open, then audited the ledger against the mock's records.\n\n")

	p.f("## Result\n\n")
	p.f("| | Count | Target |\n|---|---:|---:|\n")
	p.f("| Ledger discrepancies vs. mock-recorded usage | **%d** | 0 |\n", h.Discrepancies)
	p.f("| Double charges | **%d** | 0 |\n", h.DoubleCharges)
	p.f("| Orphaned reservations | **%d** | 0 |\n\n", h.Orphans)
	p.f("- **Discrepancies** add up three counts:\n")
	p.f("  - Charges whose target or token counts differ from the mock's record of the attempt that served the request: %d. ", a.Violations[ledger.CheckProviderUsage])
	p.f("This compared %d charges made by the gateway and %d made by the reconciler. The reconciler charges from the mock's records, so its charges agree by construction; the gateway's agreeing is the evidence.\n",
		a.Gateway.Compared, a.Reconciler.Compared)
	p.f("  - Requests the mock billed that the ledger closed without a charge: %d.\n", a.BilledNotCharged)
	p.f("  - Requests the mock billed that the ledger has no reservation for: %d.\n", ch.BilledUnknown)
	p.f("- **Double charges** are requests with more than one charge entry. The unique index on `(request_id, kind)` rules them out in the schema; this checks that end to end. ")
	p.f("Requests with more than one close entry: %d.\n", ch.DoubleCloses)
	p.f("- **Orphaned reservations** are reservations still open after the reconciler ran. %d were open once the gateway's own closes had finished, before the final pass; ", ch.OpenBeforeReconcile)
	p.f("the in-process reconciler had already closed others during the run.\n\n")

	p.f("## Every check\n\n")
	p.f("| Check | Failures |\n|---|---:|\n")
	for _, c := range []struct{ name, desc string }{
		{ledger.CheckAccountTotals, "each key's spent and held totals equal what its entries add up to"},
		{ledger.CheckStructure, "no close or charge without a reservation, no charge without a close"},
		{ledger.CheckCloseAmount, "each release returns the reservation minus the charge"},
		{ledger.CheckCost, "each charge equals its tokens at the price snapshot taken when it was reserved"},
		{ledger.CheckProviderUsage, "each charge matches the mock's record"},
		{ledger.CheckOpen, "no reservation left open"},
	} {
		p.f("| `%s`: %s | %d |\n", c.name, c.desc, a.Violations[c.name])
	}
	p.f("| Complete responses whose reported usage differs from the charge | %d |\n\n", ch.ClientMismatched)
	p.f("Of the complete responses that reported usage, %d matched the ledger's charge exactly. %d were streams that did not ask for usage.\n\n", ch.ClientMatched, ch.ClientNoUsage)

	p.f("## Where the requests went\n\n")
	p.f("| What the client saw | Requests |\n|---|---:|\n")
	p.f("| Complete response | %d |\n", res.Load.OK)
	for _, k := range sortedKeys(res.Load.Errors) {
		p.f("| %s | %d |\n", k, res.Load.Errors[k])
	}
	p.f("| **Sent** | **%d** |\n\n", res.Load.Sent)
	p.f("Failed requests are expected: a request in flight when the gateway dies loses its connection, and one sent while it is down is refused. What matters is how the ledger closed them.\n\n")
	p.f("| How the ledger closed it | Requests |\n|---|---:|\n")
	p.f("| Charged by the gateway | %d |\n", a.Gateway.Settled)
	p.f("| Charged by the reconciler, from the mock's record | %d |\n", a.Reconciler.Settled)
	for _, reason := range sortedKeys(a.Released) {
		p.f("| Released, `%s` | %d |\n", reason, a.Released[reason])
	}
	p.f("| Still open | %d |\n", a.Open)
	p.f("| **Reserved** | **%d** |\n\n", a.Requests)
	if n := a.Gateway.Estimated + a.Reconciler.Estimated; n > 0 {
		p.f("%d charges used estimated counts and were not compared with the mock.\n\n", n)
	}
	p.f("A request that never reached the gateway, or was refused before its reservation, has no ledger entries, so fewer requests are reserved than sent.\n\n")

	if len(res.Samples) > 0 || len(a.Samples) > 0 {
		p.f("## Failures\n\n")
		for _, s := range append(append([]string(nil), a.Samples...), res.Samples...) {
			p.f("- %s\n", s)
		}
		p.f("\n")
	}

	p.f("## Kills\n\n")
	p.f("| # | At (s) | Signal | Client requests in flight | Down for (s) |\n|---:|---:|---|---:|---:|\n")
	for i, k := range res.Kills {
		p.f("| %d | %.1f | SIG%s | %d | %.1f |\n", i+1, k.AtMs/1000, k.Signal, k.InFlight, k.DownMs/1000)
	}
	p.f("\n\"Down for\" runs from the kill until `/readyz` answered again.\n")
	return p.err
}

func pct(share string) string {
	var f float64
	if _, err := fmt.Sscan(share, &f); err != nil {
		return share
	}
	return fmt.Sprintf("%.0f%%", f*100)
}

func orUnknown(s string) string {
	if s == "" {
		return "not recorded"
	}
	return s
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
