#!/bin/sh
# Measures Postgres alone, inside the benchmark stack's Postgres container:
# commit latency for single-row updates at a fixed rate, with and without
# waiting for the WAL to reach disk, and the most updates per second one row
# and 16 rows can take. The gateway's reservations and settlements are
# single-row updates of a key's account, so these bound what it can do on the
# same machine. Prints Markdown.
#
# Run by scripts/bench.sh postgres, which feeds it to sh in the container.
set -eu
RATE=${RATE:-1000}
CLIENTS=${CLIENTS:-8}
SECS=${SECS:-60}
db=pgcommit

psql -U gateway -d gateway -qc "DROP DATABASE IF EXISTS $db" >/dev/null 2>&1
createdb -U gateway "$db"
pgbench -U gateway -i -s 1 -q "$db" >/dev/null 2>&1
psql -U gateway -d "$db" -qc "INSERT INTO pgbench_tellers SELECT g, 1, 0 FROM generate_series(11, 16) g" >/dev/null
echo 'UPDATE pgbench_branches SET bbalance = bbalance + 1 WHERE bid = 1;' >/tmp/one.sql
printf '%s\n' '\set t random(1, 16)' 'UPDATE pgbench_tellers SET tbalance = tbalance + 1 WHERE tid = :t;' >/tmp/sixteen.sql

# latency SYNC prints a table row for $RATE updates/s to one row. With -R,
# pgbench measures latency from each transaction's scheduled start.
latency() {
  rm -f /tmp/pgc_log*
  PGOPTIONS="-c synchronous_commit=$1" pgbench -U gateway -n -f /tmp/one.sql -c "$CLIENTS" -j 4 -R "$RATE" -T "$SECS" \
    --log --log-prefix=/tmp/pgc_log "$db" >/dev/null 2>&1
  cat /tmp/pgc_log* | awk '{print $3}' | sort -n | awk -v sync="$1" '
    { a[NR] = $1 } $1 > 50000 { slow++ }
    function p(q) { i = int(NR * q); if (i < 1) i = 1; return a[i] / 1000 }
    END { printf "| `%s` | %d | %.1f | %.1f | %.1f | %.1f | %.1f | %d |\n", sync, NR, p(.50), p(.95), p(.99), p(.999), a[NR] / 1000, slow }'
}

# throughput SCRIPT prints the updates per second pgbench reached, unthrottled.
throughput() {
  pgbench -U gateway -n -f "/tmp/$1.sql" -c "$CLIENTS" -j 4 -T 15 "$db" 2>/dev/null | awk '/^tps/ { printf "%.0f", $3 }'
}

echo "# Postgres commit latency"
echo
echo "Generated by \`scripts/pg_commit_latency.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ)${BENCH_COMMIT:+ at commit \`$BENCH_COMMIT\`}. Host: ${BENCH_HOST:-not recorded}. $(postgres --version)."
echo
echo "This measures Postgres alone, in the benchmark stack's container, with \`pgbench\`. The gateway is not involved."
echo "Every request through the gateway updates its key's account row twice, once to reserve and once to settle,"
echo "and each update holds the row's lock until its commit is durable. These numbers bound what one key can do on this machine."
echo
echo "## One row, $RATE updates/s from $CLIENTS connections, ${SECS}s"
echo
echo "Latency runs from each update's scheduled start to its commit."
echo
echo "| \`synchronous_commit\` | Updates | p50 (ms) | p95 (ms) | p99 (ms) | p99.9 (ms) | Max (ms) | Over 50 ms |"
echo "|---|---:|---:|---:|---:|---:|---:|---:|"
latency on
latency off
echo
echo "With \`on\`, the default and what the gateway uses, a commit waits until the WAL is flushed to disk. With \`off\`, it does not."
echo "Any difference in the tail is the time the disk took to flush."
echo
echo "## Most updates per second, $CLIENTS connections, 15s"
echo
echo "| Rows updated | Updates/s |"
echo "|---|---:|"
echo "| 1 | $(throughput one) |"
echo "| 16, at random | $(throughput sixteen) |"
echo
echo "These updates are lighter than the gateway's, which also insert a ledger entry under the lock."

psql -U gateway -d gateway -qc "DROP DATABASE $db" >/dev/null 2>&1
