// renderMarkdown writes res as the report committed to bench/results.
func renderMarkdown(res *Results, w io.Writer) error {
	p := &printer{w: w}
	m := res.Meta
	s := m.Settings
	p.f("# Gateway overhead\n\n")
	p.f("Generated by `scripts/loadtest` on %s", m.Date)
	if m.Commit != "" {
		p.f(" at commit `%s`", m.Commit)
	}
	p.f(". Host: %s. The load generator saw %d CPUs.\n\n", orUnknown(m.Host), m.NumCPU)
	p.f("Each level sends the same load twice: straight to the mock provider, and through the gateway to that same mock. ")
	p.f("The mock's latency is fixed: first token after %s, then %s tokens at %s tokens/s. ", s["mock_ttft"], s["mock_tokens"], s["mock_tps"])
	p.f("The direct run is the baseline, and the difference is what the gateway adds: authentication, the Redis rate limit, ")
	p.f("the Postgres reservation, routing, the extra network hop, and decoding and re-encoding every chunk. ")
	p.f("Settling the charge runs after the response, so it adds load but not latency.\n\n")
	p.f("- **Overhead** is the gateway's percentile minus the direct run's percentile, not a percentile of per-request differences. At p99 it is noisy, and it can come out negative.\n")
	p.f("- **Latency** runs from when the schedule meant to send a request to the end of its response, so a generator that falls behind shows up as latency instead of hiding it.\n")
	p.f("- **Fixed rate** sends a request every 1/rate seconds whatever the earlier ones are doing. **Fixed concurrency** keeps that many requests in flight, each worker sending its next request when the last one ends.\n")
	p.f("- Each level runs %s unmeasured, then %s measured. Benchmark keys have rate limits and a budget far above the load, so every request takes the full rate-limit and budget path.\n", s["warmup"], s["duration"])
	p.f("- The generator, gateway, mock, Postgres and Redis share one Docker VM on one laptop, so these numbers compare the two paths. They are not a server's capacity.\n\n")

	rate := filter(res.Cells, func(c Cell) bool { return c.Rate > 0 && c.Keys <= 1 })
	conc := filter(res.Cells, func(c Cell) bool { return c.Workers > 0 })
	if len(rate) > 0 {
		p.f("## Fixed rate\n\n")
		p.section(rate, "Rate (req/s)", func(c Cell) string { return fmt.Sprintf("%g", c.Rate) }, false)
	}
	if len(conc) > 0 {
		p.f("## Fixed concurrency\n\n")
		p.section(conc, "Workers", func(c Cell) string { return fmt.Sprint(c.Workers) }, true)
	}
	p.spread(res.Cells)
	p.serverMetric(res.Cells)
	p.errors(res.Cells)
	return p.err
}

type printer struct {
	w   io.Writer
	err error
}

func (p *printer) f(format string, args ...any) {
	if p.err == nil {
		_, p.err = fmt.Fprintf(p.w, format, args...)
	}
}

// pair is one load level's direct and gateway cells.
type pair struct{ direct, gateway Cell }

func pairs(cells []Cell, stream bool) []pair {
	var out []pair
	var direct *Cell
	for _, c := range cells {
		if c.Stream != stream {
			continue
		}
		switch c.Target {
		case "direct":
			direct = &c
		case "gateway":
			if direct != nil && direct.Rate == c.Rate && direct.Workers == c.Workers {
				out = append(out, pair{*direct, c})
			}
			direct = nil
		}
	}
	return out
}

func (p *printer) section(cells []Cell, level string, label func(Cell) string, throughput bool) {
	type table struct {
		title  string
		stream bool
		dist   func(Cell) bench.Dist
	}
	ttft := func(c Cell) bench.Dist {
		if c.TTFT == nil {
			return bench.Dist{}
		}
		return *c.TTFT
	}
	full := func(c Cell) bench.Dist { return c.Latency }
	for _, t := range []table{
		{"Streaming: time to first token", true, ttft},
		{"Streaming: full response", true, full},
		{"Non-streaming: full response", false, full},
	} {
		ps := pairs(cells, t.stream)
		if len(ps) == 0 {
			continue
		}
		p.f("### %s\n\n", t.title)
		if throughput {
			p.f("| %s | Throughput direct / gateway (req/s) | Direct p50 / p95 / p99 (ms) | Gateway p50 / p95 / p99 (ms) | **Overhead p50 / p95 / p99 (ms)** | Errors |\n", level)
			p.f("|---:|---:|---:|---:|---:|---:|\n")
		} else {
			p.f("| %s | In flight, mean | Direct p50 / p95 / p99 (ms) | Gateway p50 / p95 / p99 (ms) | **Overhead p50 / p95 / p99 (ms)** | Errors |\n", level)
			p.f("|---:|---:|---:|---:|---:|---:|\n")
		}
		for _, pr := range ps {
			d, g := t.dist(pr.direct), t.dist(pr.gateway)
			second := fmt.Sprintf("%.0f / %.0f", pr.direct.InFlightMean, pr.gateway.InFlightMean)
			if throughput {
				second = fmt.Sprintf("%.0f / %.0f", pr.direct.Throughput, pr.gateway.Throughput)
			}
			p.f("| %s | %s | %s | %s | **%s** | %s |\n", label(pr.gateway), second, triple(d), triple(g),
				diff(d, g), errorsCell(pr.direct, pr.gateway))
		}
		p.f("\n")
	}
}

// spread compares one key with many at the same rate.
func (p *printer) spread(cells []Cell) {
	var rows []string
	for _, c := range cells {
		if c.Keys <= 1 || c.Rate == 0 {
			continue
		}
		var one, direct *Cell
		for i := range cells {
			o := cells[i]
			if o.Stream == c.Stream && o.Rate == c.Rate && o.Workers == 0 {
				switch {
				case o.Target == "direct":
					direct = &cells[i]
				case o.Keys == 1:
					one = &cells[i]
				}
			}
		}
		if one == nil || direct == nil {
			continue
		}
		pick := func(x Cell) bench.Dist {
			if x.Stream && x.TTFT != nil {
				return *x.TTFT
			}
			return x.Latency
		}
		mode := "Non-streaming, full response"
		if c.Stream {
			mode = "Streaming, first token"
		}
		rows = append(rows, fmt.Sprintf("| %s | %g | %s | %s | %s |", mode, c.Rate,
			diff(pick(*direct), pick(*one)), diff(pick(*direct), pick(c)), errorsCell(*one, c)))
		if len(rows) == 1 {
			p.f("## One key vs. %d keys\n\n", c.Keys)
			p.f("Every request reserves against its key's account row and settles against it afterwards, and both statements lock that row. ")
			p.f("With one key, every request in flight contends for the same row; spread over %d keys, each row sees 1/%d of the load.\n\n", c.Keys, c.Keys)
			p.f("| Mode | Rate (req/s) | Overhead p50 / p95 / p99 (ms), 1 key | Overhead p50 / p95 / p99 (ms), %d keys | Errors |\n", c.Keys)
			p.f("|---|---:|---:|---:|---:|\n")
		}
	}
	for _, r := range rows {
		p.f("%s\n", r)
	}
	if len(rows) > 0 {
		p.f("\n")
	}
}

// serverMetric compares the gateway's own overhead metric with the client's measurement.
func (p *printer) serverMetric(cells []Cell) {
	var rows []string
	for _, stream := range []bool{true, false} {
		for _, pr := range pairs(filter(cells, func(c Cell) bool { return c.Keys <= 1 }), stream) {
			if pr.gateway.ServerOverheadMs == nil {
				continue
			}
			mode := "Non-streaming"
			if stream {
				mode = "Streaming"
			}
			load := fmt.Sprintf("%g req/s", pr.gateway.Rate)
			if pr.gateway.Rate == 0 {
				load = fmt.Sprintf("%d workers", pr.gateway.Workers)
			}
			rows = append(rows, fmt.Sprintf("| %s | %s | %.2f | %.2f |", mode, load,
				pr.gateway.Latency.Mean-pr.direct.Latency.Mean, *pr.gateway.ServerOverheadMs))
		}
	}
	if len(rows) == 0 {
		return
	}
	p.f("## The gateway's own overhead metric\n\n")
	p.f("`gateway_overhead_seconds` is each request's total time minus the time spent waiting on the provider, measured inside the gateway (design D23). ")
	p.f("The client's figure is the difference in mean full-response latency, so it also includes the extra network hop, ")
	p.f("and any time the generator's own scheduling added to one run and not the other.\n\n")
	p.f("| Mode | Load | Client-measured mean overhead (ms) | `gateway_overhead_seconds` mean (ms) |\n")
	p.f("|---|---:|---:|---:|\n")
	for _, r := range rows {
		p.f("%s\n", r)
	}
	p.f("\n")
}

func (p *printer) errors(cells []Cell) {
	var rows []string
	for _, c := range cells {
		for _, kind := range sortedKeys(c.ErrorKinds) {
			rows = append(rows, fmt.Sprintf("| %s | %s | %d |", describe(c), kind, c.ErrorKinds[kind]))
		}
	}
	p.f("## Errors\n\n")
	if len(rows) == 0 {
		var n int
		for _, c := range cells {
			n += c.Requests
		}
		p.f("None: all %d measured requests succeeded.\n", n)
		return
	}
	p.f("| Level | Error | Count |\n|---|---|---:|\n")
	for _, r := range rows {
		p.f("%s\n", strings.ReplaceAll(r, "\n", " "))
	}
}

func filter(cells []Cell, keep func(Cell) bool) []Cell {
	var out []Cell
	for _, c := range cells {
		if keep(c) {
			out = append(out, c)
		}
	}
	return out
}

func triple(d bench.Dist) string {
	if d.N == 0 {
		return "–"
	}
	return fmt.Sprintf("%.1f / %.1f / %.1f", d.P50, d.P95, d.P99)
}

func diff(direct, gateway bench.Dist) string {
	if direct.N == 0 || gateway.N == 0 {
		return "–"
	}
	return fmt.Sprintf("%.2f / %.2f / %.2f", gateway.P50-direct.P50, gateway.P95-direct.P95, gateway.P99-direct.P99)
}

func errorsCell(cs ...Cell) string {
	var errs, n int
	for _, c := range cs {
		errs += c.Errors
		n += c.Requests
	}
	if errs == 0 {
		return "0"
	}
	return fmt.Sprintf("%d of %d", errs, n)
}

func orUnknown(s string) string {
	if s == "" {
		return "not recorded"
	}
	return s
}
