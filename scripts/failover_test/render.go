func renderFile(path string, w io.Writer) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var res Results
	if err := json.Unmarshal(b, &res); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if len(res.Scenarios) == 0 {
		return errors.New(path + ": no scenarios")
	}
	return renderMarkdown(&res, w)
}

type printer struct {
	w   io.Writer
	err error
}

func (p *printer) f(format string, args ...any) {
	if p.err == nil {
		_, p.err = fmt.Fprintf(p.w, format, args...)
	}
}

func renderMarkdown(res *Results, w io.Writer) error {
	p := &printer{w: w}
	m, s := res.Meta, res.Meta.Settings
	p.f("# Failover under load\n\n")
	p.f("Generated by `scripts/failover_test` on %s", m.Date)
	if m.Commit != "" {
		p.f(" at commit `%s`", m.Commit)
	}
	p.f(". Host: %s.\n\n", orUnknown(m.Host))
	p.f("The `failover` alias sends requests to `primary` first and fails over to `backup` (priority policy). ")
	p.f("Both are mock providers that answer after %s, then send %s tokens at %s tokens/s. ", s["mock_ttft"], s["mock_tokens"], s["mock_tps"])
	p.f("Load is %s req/s from one key, alternating streaming and non-streaming. ", s["rate"])
	p.f("After %s of healthy load the primary starts failing; the fault lasts %s, and load continues until the primary's breaker has closed again.\n\n", s["before"], s["fault"])
	p.f("The gateway runs with its defaults: an attempt that has produced no output after `ATTEMPT_TTFT_TIMEOUT` (10s) is abandoned. ")
	p.f("A breaker opens after 5 failures in a row, or a failure rate of 50%% over at least 5 attempts in 10s. ")
	p.f("It stays open 5s, then lets one probe through; a failed probe reopens it for twice as long, up to 60s, and 2 successful probes close it. ")
	p.f("Breaker states come from polling the gateway's `/metrics` every %s, so the times below are accurate to about that.\n\n", s["poll"])
	p.f("A request is counted in the phase in which it was **sent**. An error is any response that was not complete and well formed: ")
	p.f("an error status, a dropped connection, or a stream that ended without `[DONE]`.\n\n")

	p.f("## Summary\n\n")
	p.f("| Fault | Breaker opened | Latency added until it opened, p50 / max | Errors until it opened | Errors during the fault | Breaker closed after the fix |\n")
	p.f("|---|---:|---:|---:|---:|---:|\n")
	for _, sc := range res.Scenarios {
		detecting, during := sc.phaseErrors(true), sc.phaseErrors(false)
		p.f("| `%s`: %s | %s | %s | %s | %s | %s |\n", sc.Name, sc.Fault, secs(sc.BreakerOpenMs), sc.addedLatency(),
			detecting, during, secsFrom(sc.BreakerClosedMs, sc.ClearedMs))
	}
	p.f("\nThe breaker opened this long after the fault started, and closed this long after it was removed. ")
	p.f("Added latency compares requests sent before the breaker opened with those sent before the fault.\n\n")

	for _, sc := range res.Scenarios {
		p.f("## `%s`: %s\n\n", sc.Name, sc.Fault)
		var states []string
		for _, st := range sc.States {
			states = append(states, fmt.Sprintf("%s at %.2fs", st.State, st.AtMs/1000))
		}
		p.f("Breaker states seen: %s. The fault was removed at %.2fs.", strings.Join(states, ", "), sc.ClearedMs/1000)
		if len(sc.Transitions) > 0 {
			var ts []string
			for _, to := range breakerStates {
				if n := sc.Transitions[to]; n > 0 {
					ts = append(ts, fmt.Sprintf("%d to %s", n, to))
				}
			}
			p.f(" The gateway counted %s.", strings.Join(ts, ", "))
		}
		p.f("\n\n")
		p.f("| Requests sent | From (s) | To (s) | Requests | Errors (streaming) | Served by primary / backup | Took 2+ attempts | Latency p50 / p99 / max (ms) |\n")
		p.f("|---|---:|---:|---:|---:|---:|---:|---:|\n")
		for _, ph := range sc.Phases {
			p.f("| %s | %.2f | %.2f | %d | %d (%d) | %d / %d | %d | %s |\n", ph.Name, ph.FromMs/1000, ph.ToMs/1000,
				ph.Requests, ph.Errors, ph.StreamErrors, ph.ServedBy[primaryName(res)], ph.ServedBy[backupName(res)],
				ph.Retried, latency(ph))
		}
		p.f("\n")
		kinds := map[string]int{}
		for _, ph := range sc.Phases {
			for k, n := range ph.ErrorKinds {
				kinds[k] += n
			}
		}
		if len(kinds) > 0 {
			p.f("Errors by kind: ")
			var parts []string
			for _, k := range sortedKeys(kinds) {
				parts = append(parts, fmt.Sprintf("`%s` × %d", k, kinds[k]))
			}
			p.f("%s.\n\n", strings.Join(parts, ", "))
		}
	}
	return p.err
}

// phaseErrors formats the errors among requests sent while the breaker was
// still closed (detecting), or during the whole fault.
func (sc Scenario) phaseErrors(detecting bool) string {
	var errs, streamErrs, n int
	for _, ph := range sc.Phases {
		inFault := ph.FromMs >= 0 && ph.ToMs <= sc.ClearedMs
		if !inFault || (detecting && ph.Name != phaseDetecting) {
			continue
		}
		errs += ph.Errors
		streamErrs += ph.StreamErrors
		n += ph.Requests
	}
	if n == 0 {
		return "–"
	}
	out := fmt.Sprintf("%d of %d", errs, n)
	if errs > 0 && streamErrs == errs {
		out += ", all streaming"
	}
	return out
}

// addedLatency compares requests sent while the breaker was still closed
// with those sent before the fault.
func (sc Scenario) addedLatency() string {
	var before, detecting *Phase
	for i := range sc.Phases {
		switch sc.Phases[i].Name {
		case phaseBefore:
			before = &sc.Phases[i]
		case phaseDetecting:
			detecting = &sc.Phases[i]
		}
	}
	if before == nil || detecting == nil || before.Latency.N == 0 || detecting.Latency.N == 0 {
		return "–"
	}
	return fmt.Sprintf("%s / %s", ms(detecting.Latency.P50-before.Latency.P50), ms(detecting.Latency.Max-before.Latency.P50))
}

func ms(v float64) string {
	if v >= 1000 || v <= -1000 {
		return fmt.Sprintf("%.2f s", v/1000)
	}
	return fmt.Sprintf("%.0f ms", v)
}

func latency(ph Phase) string {
	if ph.Latency.N == 0 {
		return "–"
	}
	return fmt.Sprintf("%.0f / %.0f / %.0f", ph.Latency.P50, ph.Latency.P99, ph.Latency.Max)
}

func primaryName(res *Results) string { return settingOr(res, "primary", "primary") }
func backupName(res *Results) string  { return settingOr(res, "backup", "backup") }

func settingOr(res *Results, key, def string) string {
	if v := res.Meta.Settings[key]; v != "" {
		return v
	}
	return def
}

func secs(ms *float64) string {
	if ms == nil {
		return "never"
	}
	return fmt.Sprintf("%.2f s", *ms/1000)
}

func secsFrom(ms *float64, from float64) string {
	if ms == nil {
		return "never"
	}
	return fmt.Sprintf("%.2f s", (*ms-from)/1000)
}

func orUnknown(s string) string {
	if s == "" {
		return "not recorded"
	}
	return s
}

func sortedKeys(m map[string]int) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
